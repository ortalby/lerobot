def get_words_for_level(level: int, category: str | None = None) -> list[str]:
    """Get practice words for a given difficulty level."""
    if category and category in WORD_BANK:
        words = WORD_BANK[category]["words"]
    else:
        # Collect from all categories
        words = []
        for cat_data in WORD_BANK.values():
            words.extend(cat_data["words"])

    # Filter by word length based on difficulty
    if level == 1:
        return [w for w in words if len(w) <= 4][:20]
    elif level == 2:
        return [w for w in words if len(w) <= 6][:25]
    else:
        return words[:30]


def format_word_bank_display(category: str) -> str:
    """Format word bank for display in the UI."""
    if category not in WORD_BANK:
        return ""
    data = WORD_BANK[category]
    lines = [f"{data['emoji']} **{category}**\n"]
    lines.append("**מילים לתרגול:**")
    # Show first 15 words
    for w in data["words"][:15]:
        lines.append(f"• {w}")
    lines.append("\n**משפטים לדוגמה:**")
    for s in data["sentences"]:
        lines.append(f"• {s}")
    return "\n".join(lines)
